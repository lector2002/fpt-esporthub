type MatchingT = ReturnType<typeof useMatchingMessages>["t"];

const SLOTS = new Set(["weekday_morning", "weekday_afternoon", "weekday_evening", "weekend", "late_night", "flexible"]);

/** Translated reason label. Also usable by other features that show match reasons (dashboard). */
export function reasonLabel(t: MatchingT, code: ReasonCode) {
  return t(`reason_${code}`);
}

/** Translated schedule slot, or the raw id with underscores spaced when the slot is unknown. */
export function slotLabel(t: MatchingT, slot: string) {
  return SLOTS.has(slot) ? t(`slot_${slot}` as Parameters<MatchingT>[0]) : slot.replaceAll("_", " ");
}
