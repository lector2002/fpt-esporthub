type VoiceMessageKey = Parameters<ReturnType<typeof useVoiceMessages>["t"]>[0];

const FAILURE_KEYS: Partial<Record<string, VoiceMessageKey>> = {
  mic_denied: "errorMicDenied",
  mic_unavailable: "errorMicUnavailable",
  ice_failed: "errorIce",
  offline: "errorOffline",
  busy: "errorBusy",
  unavailable: "errorUnavailable",
  no_call: "errorNoCall",
  full: "errorFull",
  blocked: "errorBlocked",
  restricted: "errorRestricted",
  rate_limited: "errorRateLimited",
};

export function failureKey(reason: string): VoiceMessageKey {
  return FAILURE_KEYS[reason] ?? "errorGeneric";
}
