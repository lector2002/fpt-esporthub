export const useProfileMessages = defineMessages({ vi, en });

type OptionKind = "goal" | "style" | "schedule";

/** Localized label for a lookup id; falls back to the API label, then the raw id. */
export function useOptionLabel() {
  const { t } = useProfileMessages();
  return (kind: OptionKind, id: string, fallback?: string) => {
    const key = `${kind}_${id}`;
    return key in vi ? t(key as ProfileMessageKey) : (fallback ?? id);
  };
}
