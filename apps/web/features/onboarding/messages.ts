export type OnboardingT = ReturnType<typeof useOnboardingMessages>["t"];

/** Translated label for a lookup option id, or the API label when the id is unknown. */
export function optionLabel(t: OnboardingT, option: { id: string; label: string }) {
  const key = `opt_${option.id}`;
  return OPTION_KEYS.has(key) ? t(key as keyof typeof optionsVi) : option.label;
}
